import type { AppDefinition } from "../contract.js";

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

const RUNTIME = `
function revive(schema, value) {
  if (value === null || value === undefined || !schema) return value;
  switch (schema.kind) {
    case "date": return typeof value === "string" ? new Date(value) : value;
    case "optional": return revive(schema.of, value);
    case "array": return Array.isArray(value) ? value.map((v) => revive(schema.of, v)) : value;
    case "object":
    case "record": {
      const fields = schema.kind === "object" ? schema.fields : RECORDS[schema.name];
      if (!fields || typeof value !== "object") return value;
      const out = { ...value };
      for (const key of Object.keys(fields)) if (key in out) out[key] = revive(fields[key], out[key]);
      return out;
    }
    default: return value;
  }
}

function plain(value) {
  if (value instanceof Date) return value.toISOString();
  if (value !== null && typeof value === "object") return JSON.stringify(value);
  return String(value);
}

async function call(spec, input, options) {
  const opts = options || {};
  const rest = input && typeof input === "object" ? { ...input } : {};
  const path = spec.path.replace(/:([A-Za-z_]\\w*)/g, (_, name) => {
    if (rest[name] === undefined || rest[name] === null) throw new Error(spec.name + ": missing path parameter \\"" + name + "\\"");
    const value = rest[name];
    delete rest[name];
    return encodeURIComponent(plain(value));
  });
  let url = (opts.baseUrl || "") + "/api" + path;
  const init = { method: spec.method, headers: { accept: "application/json" } };
  if (opts.token) init.headers.authorization = "Bearer " + opts.token;
  const keys = Object.keys(rest).filter((k) => rest[k] !== undefined);
  if (spec.method === "GET" || spec.method === "DELETE") {
    const query = new URLSearchParams();
    for (const key of keys) {
      for (const item of Array.isArray(rest[key]) ? rest[key] : [rest[key]]) query.append(key, plain(item));
    }
    const text = query.toString();
    if (text) url += "?" + text;
  } else if (keys.length) {
    init.headers["content-type"] = "application/json";
    init.body = JSON.stringify(rest);
  }
  const response = await (opts.fetch || fetch)(url, init);
  const text = response.status === 204 ? "" : await response.text();
  let body;
  try { body = text ? JSON.parse(text) : undefined; } catch { body = undefined; }
  if (!response.ok) {
    const failure = new Error((body && body.error && body.error.message) || response.statusText || "Request failed");
    failure.status = response.status;
    failure.code = body && body.error && body.error.code;
    failure.body = body;
    throw failure;
  }
  return revive(spec.output, body);
}
`;

/** A9: the API SDK as ES module text. One exported async function per endpoint, each `(input, { token, baseUrl?,
 * fetch? })`. Path parameters are filled from `input`, the rest of a GET's input goes in the query string, the rest
 * of any other call's in a JSON body. A failed call throws an `Error` with `status`, `code` and `body`. Dates in
 * the reply are made into `Date`s. */
export function generateSdk(app: AppDefinition): string {
  const records = Object.fromEntries(app.records.map((r) => [r.name, r.fields]));
  const out: string[] = [
    "// Generated by Thixo from the app's API. Do not edit.",
    `const RECORDS = ${JSON.stringify(records)};`,
    RUNTIME.trim(),
  ];
  for (const e of app.endpoints) {
    if (!IDENTIFIER.test(e.name)) throw new Error(`Endpoint name "${e.name}" is not a valid identifier, so it can't be an SDK function`);
    const spec = { name: e.name, method: e.method, path: e.path, output: e.output };
    out.push(`export async function ${e.name}(input, options) {\n  return call(${JSON.stringify(spec)}, input, options);\n}`);
  }
  return out.join("\n\n") + "\n";
}
